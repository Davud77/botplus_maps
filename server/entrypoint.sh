#!/bin/bash
# server/entrypoint.sh

# Останавливаем скрипт при возникновении любых ошибок
set -e

# Multipart spooling and GDAL scratch must use the configured data filesystem.
if [ -n "${TMPDIR:-}" ]; then
    mkdir -p "$TMPDIR"
    test -w "$TMPDIR"
fi

echo "====================================================="
echo "  🚀 Запуск процесса инициализации Backend"
echo "====================================================="

# 1. Автоматически проверяем, какая среда задана в .env
if [ "$APP_ENV" = "production" ]; then
    echo "🌍 Режим: PRODUCTION (Прод)"
    echo "🔒 Ожидается использование HTTPS и безопасных Cookie."
    # Здесь можно добавить команды, которые нужны ТОЛЬКО на проде
    # Например, применение строгих миграций БД
else
    echo "💻 Режим: DEVELOPMENT (Локальная разработка)"
    echo "🔓 Работа по HTTP, CORS открыт для localhost."
    # Здесь можно добавить команды для локальной разработки
    # Например, загрузка тестовых (mock) данных
fi

echo "-----------------------------------------------------"
echo "📦 Инициализация базы данных и таблиц..."

# 2. Выполняем скрипт создания таблиц (без стандартных аккаунтов)
python server/init_pg_auth.py

echo "✅ Инициализация БД успешно завершена."
echo "-----------------------------------------------------"

echo "⚙️  Запуск основного процесса приложения (Gunicorn / Flask)..."
echo "====================================================="

# 3. Выполняем команду, переданную Docker'ом (gunicorn ...)
# exec заменяет текущий процесс bash на процесс gunicorn, 
# что позволяет Docker'у корректно управлять остановкой контейнера
exec "$@"